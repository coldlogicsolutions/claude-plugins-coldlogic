#!/usr/bin/env bash
# Reports any part of the shared setup that has fallen behind, with the
# command that fixes it. Prints nothing when everything is current, and never
# fails the session: every check skips itself when its tool or file is absent.
#
# The coldlogic-devenv comparison mirrors the module's
# `coldlogic:setup-freshness` task, and shares its cache of the remote's HEAD
# (`.devenv/state/coldlogic-freshness`): while the lock is current, the shell
# and the session make one lookup an hour between them. Keep the two in step.
set -uo pipefail

root="${CLAUDE_PROJECT_DIR:-$PWD}"
findings=()

# Runs a command with a time limit, without relying on coreutils' `timeout`,
# which a stock macOS lacks.
with_timeout() {
  local secs="$1"
  shift
  if command -v timeout >/dev/null 2>&1; then
    timeout "$secs" "$@"
    return
  fi
  "$@" &
  local pid=$!
  (sleep "$secs" && kill "$pid" 2>/dev/null) &
  local watcher=$!
  wait "$pid"
  local status=$?
  kill "$watcher" 2>/dev/null
  return "$status"
}

# 1. coldlogic-devenv locked behind its remote HEAD.
lock="$root/devenv.lock"
if [[ -f "$lock" ]] && command -v jq >/dev/null 2>&1 && command -v git >/dev/null 2>&1; then
  node=$(jq -c '.nodes."coldlogic-devenv".locked // empty' "$lock")
  if [[ -n "$node" ]]; then
    locked=$(jq -r '.rev // empty' <<<"$node")
    case "$(jq -r '.type' <<<"$node")" in
      github) remote="https://github.com/$(jq -r '"\(.owner)/\(.repo)"' <<<"$node")" ;;
      git) remote=$(jq -r '.url' <<<"$node") ;;
      *) remote="" ;; # a local path: input while developing the module
    esac
    if [[ -n "$locked" && -n "$remote" ]]; then
      # `<time> <remote> <rev>`. Only an entry that says the lock is current
      # is used, so an update or a torn write just looks again.
      cache="$root/.devenv/state/coldlogic-freshness"
      now=$(date +%s)
      latest="" at="" cached_remote="" cached_rev=""
      { read -r at cached_remote cached_rev <"$cache"; } 2>/dev/null || true
      [[ $at =~ ^[0-9]+$ ]] || at=0
      age=$((now - 10#$at)) # 10#: a leading zero would otherwise mean octal
      if [[ $cached_remote == "$remote" && $cached_rev == "$locked" ]] && ((age >= 0 && age < 3600)); then
        latest=$cached_rev
      else
        latest=$(GIT_TERMINAL_PROMPT=0 with_timeout 3 git ls-remote "$remote" HEAD 2>/dev/null | cut -f1)
        if [[ -n "$latest" ]]; then
          { mkdir -p "${cache%/*}" && echo "$now $remote $latest" >"$cache"; } 2>/dev/null || true
        fi
      fi
      if [[ -n "$latest" && "$latest" != "$locked" ]]; then
        findings+=("coldlogic-devenv is behind (locked ${locked:0:7}, latest ${latest:0:7}); run: devenv update coldlogic-devenv")
      fi
    fi
  fi
fi

# 2. OpenSpec skills generated by a different CLI version than the one on PATH.
if command -v openspec >/dev/null 2>&1 && [[ -d "$root/.claude/skills" ]]; then
  cli=$(openspec --version 2>/dev/null | head -n1 | tr -d '[:space:]')
  generated=$(grep -ho 'generatedBy: *"[^"]*"' "$root"/.claude/skills/openspec-*/SKILL.md 2>/dev/null |
    sed 's/.*"\(.*\)"/\1/' | sort -u | paste -sd, -)
  if [[ -n "$cli" && -n "$generated" && "$generated" != "$cli" ]]; then
    findings+=("OpenSpec skills were generated by $generated but the CLI is $cli; run: openspec update")
  fi
fi

# 3. Auto-installed plugins that nothing requires any more.
if command -v claude >/dev/null 2>&1; then
  for scope in project user; do
    out=$(cd "$root" && with_timeout 5 claude plugin prune --dry-run --scope "$scope" 2>/dev/null)
    if [[ -n "$out" && "$out" != Nothing\ to\ prune* ]]; then
      findings+=("Unneeded auto-installed plugins at $scope scope; run: claude plugin prune --scope $scope")
    fi
  done
fi

if ((${#findings[@]} > 0)); then
  echo "The shared Cold Logic setup is out of date. Mention this to the user once, at the start of your first reply, with the fix for each item:"
  printf -- '- %s\n' "${findings[@]}"
fi
exit 0
